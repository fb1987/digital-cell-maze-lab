def fixture_sources():
    items={};last={};rng=random.Random(202610210118)
    for k,identity in enumerate(m.TARGETS):
        p=random_genome(rng).to_dict()
        p['blocks'][6][0]=Gene(10,12,3,4,0,0,64).row()
        child=deepcopy(p);n=len(p['blocks'][6]);child['blocks'][6].append(Gene(10,12+n,3,4,0,0,64).row())
        root=random_genome(rng).to_dict();rootid='m7/reference/anchor/0' if k==1 else 'fixture/root0'
        items[identity]=dict(id=identity,genome=child,parent=f'fixture/parent{k}',root=rootid)
        items[f'fixture/parent{k}']=dict(id=f'fixture/parent{k}',genome=p)
        items[rootid]=dict(id=rootid,genome=root)
        last[identity]=dict(events=[dict(kind='duplicate_node',block=6,index=0)])
    return dict(items=items,last_births=last,protected=['m7/reference/anchor/0'])

def test_fixed_synthetic_panel_is_valid_reproducible_and_nonadaptive():
    src=fixture_sources();a=m.make_panel(src);assert a==m.make_panel(deepcopy(src))
    assert a['no_reproduction'] and not a['invalid_restorations']
    for i,x in a['items'].items():
        if x['representation']=='modular':assert Genome.from_dict(x['genome']).instructions<=256
    for k in (0,1):
        assert a['items'][f'a{k}/restore/000']['genome']==src['items'][m.TARGETS[k]]['genome']
        root=src['items'][src['items'][m.TARGETS[k]]['root']]['genome']
        assert a['items'][f'a{k}/restore/255']['genome']==root
        for ch in range(8):
            original=src['items'][m.TARGETS[k]]['genome'];g=a['items'][f'a{k}/zero/{ch}']['genome']
            assert g['ports']==original['ports'] and g['blocks'][ch][:-1]==original['blocks'][ch][:-1]
            assert g['blocks'][ch][-1]==[1,original['blocks'][ch][-1][1],0,0,0,0,64]
    for ch in (3,4):
        g=a['items'][f'a0/c6_only_channel{ch}']['genome']
        assert g['blocks'][6][-1][0]==0 and g['ports'][6][g['blocks'][6][-1][2]]==ch

def test_readout_preserves_prefix_and_has_no_self_forward_reference():
    src=fixture_sources();a=m.make_panel(src)
    for k in (0,1):
        for role,identity in [('child',m.TARGETS[k]),('parent',f'fixture/parent{k}')]:
            g=src['items'][identity]['genome'];last=len(g['blocks'][6])-1
            for node in range(last+1):
                x=a['items'][f'a{k}/{role}_readout/{node:02d}']['genome']
                assert x['ports']==g['ports'] and x['blocks'][6][:-1]==g['blocks'][6][:-1]
                if node==last:assert x==g
                else:assert x['blocks'][6][-1]==[0,12+last,12+node,0,0,0,64]

def test_exact_allocation_and_dedup():
    panel=m.make_panel(fixture_sources());tasks=m.specs(panel,['a','b'])
    aliases=[i for t in tasks for e in t for i in e['aliases']]
    assert sorted(aliases)==sorted(panel['items']) and len(aliases)==len(set(aliases))
    assert all(e['queries']==['a','b'] for t in tasks for e in t)
    assert len(tasks)*1680<=m.CONFIG['call_cap']

def test_summary_and_all_native_audit_on_excluded_saved_fixtures(tmp_path,monkeypatch):
    # Two engineering-model responses already evaluated on excluded M7 fixtures.
    # No actual M8 diagnostic panel or fresh maze is generated by this test.
    old=m.ROOT/'results/breeding_allocation';data=m.readz(old/'final_fixture.json.gz')
    control=m.readz(old/'final_control_fixture.json.gz')['entries'];controls=m.controls()
    out=tmp_path/'results';out.mkdir();run=tmp_path/'run';run.mkdir()
    names=[f'a{k}/{role}' for k in (0,1) for role in ('child','root','parent','parent_child_writer')]
    names += [f'a{k}/zero/{ch}' for k in (0,1) for ch in range(8)]
    names += ['protected/m7/reference/anchor/0']
    panel=dict(items={i:dict(genome=controls[1]['genome'],representation='modular',kind='unchanged') for i in names})
    for c in controls:panel['items'][c['id']]=dict(genome=c['genome'],representation=c['representation'],kind='engineering_control')
    specs=m.specs(panel,data['queries']['all']);saved={hashed(packed({k:c[k] for k in ('genome','representation')})):r['rows'] for c,r in zip(controls,control)}
    m.writez(out/'sources.json.gz',{});m.writez(out/'panel.json.gz',panel);m.writez(out/'cases.json.gz',data)
    j=Journal(run);j.initialize(m.CONFIG,{},set());n=j.prepare(data,specs)
    for k,t in enumerate(specs):
        e=t[0];rs=saved[hashed(packed(e['model']))];work=sum(r['reads']+r['dispatches']+r['exposure_checks'] for r in rs)
        receipt=dict(entries=[dict(aliases=e['aliases'],rows=rs)],calls=len(rs),work=work,candidate_seconds=0,cpu_seconds=0,independently_graded=len(rs))
        j.reserve(n,k,len(rs),work);j.receipt(n,k,receipt,work)
    j.commit(n,j.state(),dict(no_selection=True,no_evolution=True));j.close()
    monkeypatch.setattr(m,'OUT',out);monkeypatch.setattr(m,'RUN',run);monkeypatch.setattr(m,'check',lambda:m.CONFIG)
    monkeypatch.setattr(m,'make_panel',lambda _:panel);monkeypatch.setattr(m,'confirmation',lambda *_:deepcopy(data))
    m.analyze();s=json.loads((out/'summary.json').read_text());assert s['ordinary_bases']==256
    assert all(sum(v['bases'] for v in x['ordinary_length_strata'].values())==256 for x in s['models'].values())
    assert not s['primary_repair_replication'] and not s['diagnostic_upstream_hits']
    m.audit();a=json.loads((out/'audit.json').read_text());assert a['status']=='PASS' and a['native_replays']==a['independent_grades']==2*1680
    assert a['conventional_calls']==3*1680
